param([Parameter(Mandatory = $true)][string]$UnicodeDataPath, [Parameter(Mandatory = $true)][string]$NormalizationPropsPath)

# Generates UnicodeIdentifierData.cs, the Unicode data of Names (SPEC 2.5, F.2.2) and of the one NFC check, which IdentifierHelper
# reads: each scalar's properties (1 NameStart: Lu, Ll, Lt, Lm, Lo, Nl; 2 NameContinue: NameStart, Mn, Mc, Nd, Pc; the canonical
# combining class << 2; 1024 NFC_QC No; 2048 NFC_QC Maybe; 4096 Lu), the canonical decompositions
# (UnicodeData.txt) and the primary composites (two-scalar canonical decompositions without Full_Composition_Exclusion). Hangul
# syllables are algorithmic and have no rows. The inputs are the unmodified Unicode 15.0.0 files; pass their paths, the files are
# data only.
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/IntegerTable.ps1"
$unicodeDataExpected = '806E9AED65037197F1EC85E12BE6E8CD870FC5608B4DE0FFFD990F689F376A73'
if ((Get-FileHash -LiteralPath $UnicodeDataPath -Algorithm SHA256).Hash -ne $unicodeDataExpected) {
    throw 'Expected the unmodified Unicode 15.0.0 UnicodeData.txt.'
}

$normalizationExpected = 'D5687A48C95C7D6E1EC59CB29C0F2E8B052018EB069A4371B7368D0561E12A29'
if ((Get-FileHash -LiteralPath $NormalizationPropsPath -Algorithm SHA256).Hash -ne $normalizationExpected) {
    throw 'Expected the unmodified Unicode 15.0.0 DerivedNormalizationProps.txt.'
}

# Each scalar's properties; a <..., First> and <..., Last> pair of UnicodeData.txt assigns the scalars between them.
$properties = [int[]]::new(0x110000)
$decompositions = [System.Collections.Generic.List[int]]::new()
$rangeFirst = 0
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $UnicodeDataPath))) {
    $fields = $line.Split(';')
    $scalar = [Convert]::ToInt32($fields[0], 16)
    if ($fields[1].EndsWith(', First>')) { $rangeFirst = $scalar; continue }
    $category = $fields[2]
    $value = if ($category -in @('Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Nl')) { 3 } elseif ($category -in @('Mn', 'Mc', 'Nd', 'Pc')) { 2 } else { 0 }
    $value += [int]$fields[3] -shl 2
    if ($category -eq 'Lu') { $value += 4096 }
    $first = if ($fields[1].EndsWith(', Last>')) { $rangeFirst } else { $scalar }
    for ($s = $first; $s -le $scalar; $s++) { $properties[$s] = $value }
    if ($fields[5].Length -eq 0 -or $fields[5][0] -eq '<') { continue }
    $parts = $fields[5].Split(' ')
    if ($parts.Count -gt 2) { throw 'A canonical decomposition is expected to have at most two scalars.' }
    $decompositions.Add($scalar)
    $decompositions.Add([Convert]::ToInt32($parts[0], 16))
    $decompositions.Add($(if ($parts.Count -eq 2) { [Convert]::ToInt32($parts[1], 16) } else { 0 }))
}

$excluded = [System.Collections.Generic.HashSet[int]]::new()
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $NormalizationPropsPath))) {
    $data = $line.Split('#')[0]
    if ($data.Trim().Length -eq 0) { continue }
    $fields = $data.Split(';')
    $bounds = $fields[0].Trim() -split '\.\.'
    $first = [Convert]::ToInt32($bounds[0], 16)
    $last = [Convert]::ToInt32($bounds[-1], 16)
    $property = $fields[1].Trim()
    if ($property -eq 'Full_Composition_Exclusion') {
        for ($s = $first; $s -le $last; $s++) { [void]$excluded.Add($s) }
    }
    elseif ($property -eq 'NFC_QC') {
        $quickCheck = $fields[2].Trim()
        $bit = if ($quickCheck -eq 'N') { 1024 } elseif ($quickCheck -eq 'M') { 2048 } else { throw "Unexpected NFC_QC value '$quickCheck'." }
        for ($s = $first; $s -le $last; $s++) { $properties[$s] = $properties[$s] -bor $bit }
    }
}

# Ascending merged inclusive ranges of scalars with nonzero properties: (first, last, properties).
$ranges = [System.Collections.Generic.List[int]]::new()
for ($scalar = 0; $scalar -lt $properties.Length; $scalar++) {
    $value = $properties[$scalar]
    if ($value -eq 0) { continue }
    if ($ranges.Count -gt 0 -and $ranges[$ranges.Count - 2] -eq $scalar - 1 -and $ranges[$ranges.Count - 1] -eq $value) {
        $ranges[$ranges.Count - 2] = $scalar
        continue
    }

    $ranges.Add($scalar); $ranges.Add($scalar); $ranges.Add($value)
}

# Primary composites, ascending (first << 42 | second << 21 | composite).
$compositions = [System.Collections.Generic.List[UInt64]]::new()
for ($i = 0; $i -lt $decompositions.Count; $i += 3) {
    if ($decompositions[$i + 2] -eq 0 -or $excluded.Contains($decompositions[$i])) { continue }
    $compositions.Add(([UInt64]$decompositions[$i + 1] -shl 42) -bor ([UInt64]$decompositions[$i + 2] -shl 21) -bor [UInt64]$decompositions[$i])
}

$compositions.Sort()

$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// <auto-generated/>')
[void]$output.AppendLine('// Unicode 15.0.0: https://www.unicode.org/Public/15.0.0/ucd/')
[void]$output.AppendLine('// Unicode data license: https://www.unicode.org/license.txt')
[void]$output.AppendLine("// UnicodeData.txt SHA-256: $($unicodeDataExpected.ToLowerInvariant())")
[void]$output.AppendLine("// DerivedNormalizationProps.txt SHA-256: $($normalizationExpected.ToLowerInvariant())")
[void]$output.AppendLine('// Generated by GenerateIdentifierUnicode.ps1; per-scalar properties, ascending merged (first, last, properties) ranges; canonical')
[void]$output.AppendLine('// decompositions, ascending (scalar, first, second or 0); primary composites, ascending (first << 42 | second << 21 | composite);')
[void]$output.AppendLine('// little-endian bytes of 32-bit (Properties, Decompositions) and 64-bit (Compositions) integers (IntegerTable<int> and <ulong>).')
[void]$output.AppendLine('namespace Kimi.Compiler.Helper;')
[void]$output.AppendLine('')
[void]$output.AppendLine('internal static class UnicodeIdentifierData')
[void]$output.AppendLine('{')
Add-IntegerTable $output 'Properties' $ranges 32
Add-IntegerTable $output 'Decompositions' $decompositions 32
Add-IntegerTable $output 'Compositions' $compositions 64
[void]$output.AppendLine('}')
$targetPath = Join-Path $PSScriptRoot 'UnicodeIdentifierData.cs'
[IO.File]::WriteAllText($targetPath, $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Generated $($ranges.Count / 3) property ranges, $($decompositions.Count / 3) decompositions and $($compositions.Count) compositions."
