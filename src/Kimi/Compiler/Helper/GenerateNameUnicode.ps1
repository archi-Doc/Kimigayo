param([Parameter(Mandatory = $true)][string]$CaseFoldingPath, [Parameter(Mandatory = $true)][string]$UnicodeDataPath)

# Generates UnicodeNameData.cs, the Unicode data of source logical names (IMPL 20.1): simple case folding (CaseFolding.txt's C
# and S mappings) and every scalar's canonical combining class (UnicodeData.txt), which NFC reads. The inputs are the unmodified
# Unicode 15.0.0 files; pass their paths, the files are data only.
$ErrorActionPreference = 'Stop'
$expected = 'CDD49E55EAE3BBF1F0A3F6580C974A0263CB86A6A08DAA10FBF705B4808A56F7'
if ((Get-FileHash -LiteralPath $CaseFoldingPath -Algorithm SHA256).Hash -ne $expected) {
    throw 'Expected the unmodified Unicode 15.0.0 CaseFolding.txt.'
}

$unicodeDataExpected = '806E9AED65037197F1EC85E12BE6E8CD870FC5608B4DE0FFFD990F689F376A73'
if ((Get-FileHash -LiteralPath $UnicodeDataPath -Algorithm SHA256).Hash -ne $unicodeDataExpected) {
    throw 'Expected the unmodified Unicode 15.0.0 UnicodeData.txt.'
}

# Merged inclusive ranges of scalars with a nonzero canonical combining class: (first, last, class).
$classes = [System.Collections.Generic.List[int]]::new()
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $UnicodeDataPath))) {
    $fields = $line.Split(';')
    $class = [int]$fields[3]
    if ($class -eq 0) { continue }
    $scalar = [Convert]::ToInt32($fields[0], 16)
    if ($classes.Count -gt 0 -and $classes[$classes.Count - 2] -eq $scalar - 1 -and $classes[$classes.Count - 1] -eq $class) {
        $classes[$classes.Count - 2] = $scalar
        continue
    }

    $classes.Add($scalar); $classes.Add($scalar); $classes.Add($class)
}

$pairs = [System.Collections.Generic.List[int]]::new()
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $CaseFoldingPath))) {
    $data = $line.Split('#')[0]
    if ($data.Trim().Length -eq 0) { continue }
    $fields = $data.Split(';')
    if ($fields[1].Trim() -notin @('C', 'S')) { continue }
    $pairs.Add([Convert]::ToInt32($fields[0].Trim(), 16))
    $pairs.Add([Convert]::ToInt32($fields[2].Trim(), 16))
}

for ($i = 2; $i -lt $pairs.Count; $i += 2) {
    if ($pairs[$i] -le $pairs[$i - 2]) { throw 'CaseFolding.txt is expected in ascending code point order.' }
}

# Appends a table of nonnegative 32-bit integers as little-endian bytes, which Int32Table reads (DECISIONS R5-M179), 24 bytes a line.
function Add-Table([string]$name, [System.Collections.Generic.List[int]]$values) {
    $bytes = foreach ($value in $values) { for ($shift = 0; $shift -lt 32; $shift += 8) { ($value -shr $shift) -band 0xFF } }
    [void]$output.AppendLine("    internal static ReadOnlySpan<byte> $name =>")
    [void]$output.AppendLine('    [')
    for ($i = 0; $i -lt $bytes.Count; $i += 24) {
        $entries = for ($j = $i; $j -lt [Math]::Min($i + 24, $bytes.Count); $j++) { $bytes[$j] }
        [void]$output.AppendLine('        ' + ($entries -join ', ') + ',')
    }
    [void]$output.AppendLine('    ];')
}

$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// <auto-generated/>')
[void]$output.AppendLine('// Unicode 15.0.0: https://www.unicode.org/Public/15.0.0/ucd/')
[void]$output.AppendLine('// Unicode data license: https://www.unicode.org/license.txt')
[void]$output.AppendLine("// CaseFolding.txt SHA-256: $($expected.ToLowerInvariant())")
[void]$output.AppendLine("// UnicodeData.txt SHA-256: $($unicodeDataExpected.ToLowerInvariant())")
[void]$output.AppendLine('// Generated by GenerateNameUnicode.ps1; simple case folding (status C and S), ascending (scalar, folded) pairs;')
[void]$output.AppendLine('// nonzero canonical combining classes, ascending merged (first, last, class) ranges; little-endian bytes (Int32Table).')
[void]$output.AppendLine('namespace Kimi.Compiler.Helper;')
[void]$output.AppendLine('')
[void]$output.AppendLine('internal static class UnicodeNameData')
[void]$output.AppendLine('{')
Add-Table 'SimpleCaseFolding' $pairs
[void]$output.AppendLine('')
Add-Table 'CombiningClasses' $classes
[void]$output.AppendLine('}')
$targetPath = Join-Path $PSScriptRoot 'UnicodeNameData.cs'
[IO.File]::WriteAllText($targetPath, $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Generated $($pairs.Count / 2) simple case folding pairs and $($classes.Count / 3) combining class ranges."
