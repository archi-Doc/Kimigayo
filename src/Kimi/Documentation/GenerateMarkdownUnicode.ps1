param([Parameter(Mandatory = $true)][string]$UnicodeDataPath)

# Generates MarkdownUnicodeData.cs, CommonMark 0.31.2's two character classes (2.1), Punctuation, the P* and S* categories, and
# Whitespace, Zs plus TAB, LF, FF and CR; each as a Latin-1 map MarkdownUnicode reads below 256 and a row of merged inclusive ranges
# it reads above. The input is the unmodified Unicode 15.0.0 UnicodeData.txt; pass its path, the file is data only.
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/../Compiler/Helper/IntegerTable.ps1"
$expected = '806E9AED65037197F1EC85E12BE6E8CD870FC5608B4DE0FFFD990F689F376A73'
if ((Get-FileHash -LiteralPath $UnicodeDataPath -Algorithm SHA256).Hash -ne $expected) {
    throw 'Expected the unmodified Unicode 15.0.0 UnicodeData.txt.'
}

# Adds a scalar to a class: below 256 to its Latin-1 map, bit (scalar % 64) of word (scalar / 64), and to its row of merged inclusive
# (first, last) ranges; scalars come in ascending order.
function Add-Scalar($latin1, $ranges, [int]$scalar) {
    if ($scalar -lt 256) { $latin1[$scalar -shr 6] = $latin1[$scalar -shr 6] -bor ([UInt64]1 -shl ($scalar -band 63)) }
    if ($ranges.Count -gt 0 -and $ranges[$ranges.Count - 1] -eq $scalar - 1) { $ranges[$ranges.Count - 1] = $scalar; return }
    $ranges.Add($scalar); $ranges.Add($scalar)
}

$punctuationLatin1 = [UInt64[]]::new(4)
$punctuation = [System.Collections.Generic.List[int]]::new()
$whitespaceLatin1 = [UInt64[]]::new(4)
$whitespace = [System.Collections.Generic.List[int]]::new()
foreach ($line in [IO.File]::ReadLines((Resolve-Path -LiteralPath $UnicodeDataPath))) {
    $fields = $line.Split(';')
    $scalar = [Convert]::ToInt32($fields[0], 16)
    if ($fields[2][0] -in @('P', 'S')) { Add-Scalar $punctuationLatin1 $punctuation $scalar }
    if ($fields[2] -eq 'Zs' -or $scalar -in @(0x09, 0x0A, 0x0C, 0x0D)) { Add-Scalar $whitespaceLatin1 $whitespace $scalar }
}

$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// <auto-generated/>')
[void]$output.AppendLine('// Unicode 15.0.0: https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt')
[void]$output.AppendLine('// Unicode data license: https://www.unicode.org/license.txt')
[void]$output.AppendLine("// SHA-256: $expected")
[void]$output.AppendLine('// Generated by GenerateMarkdownUnicode.ps1; Punctuation the P* and S* categories, Whitespace Zs plus TAB, LF, FF and CR;')
[void]$output.AppendLine('// each a Latin-1 map of U+0000-U+00FF, bit (scalar % 64) of word (scalar / 64) (IntegerTable<ulong>), and a row of merged')
[void]$output.AppendLine('// inclusive ranges (IntegerTable<int>); little-endian bytes; WhitespaceLast, the last scalar of Whitespace.')
[void]$output.AppendLine('namespace Kimi.Documentation;')
[void]$output.AppendLine('internal static class MarkdownUnicodeData')
[void]$output.AppendLine('{')
Add-IntegerTable $output 'PunctuationLatin1' $punctuationLatin1 64
[void]$output.AppendLine('')
Add-IntegerTable $output 'Punctuation' $punctuation 32
[void]$output.AppendLine('')
Add-IntegerTable $output 'WhitespaceLatin1' $whitespaceLatin1 64
[void]$output.AppendLine('')
Add-IntegerTable $output 'Whitespace' $whitespace 32
[void]$output.AppendLine('')
[void]$output.AppendLine(('    internal const int WhitespaceLast = 0x{0:X};' -f $whitespace[$whitespace.Count - 1]))
[void]$output.AppendLine('}')
$targetPath = Join-Path $PSScriptRoot 'MarkdownUnicodeData.cs'
[IO.File]::WriteAllText($targetPath, $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Generated $($punctuation.Count / 2) punctuation/symbol ranges and $($whitespace.Count / 2) whitespace ranges, each class with its Latin-1 map."
