// Owns a file's rule identities and logical size, using the compiler's existing syntax tree.
// Input: a compilation, source tree and normalized repository path. Output: stable scopes, anchors and token counts.
// Symbol identities are resolved only for observations; local collision maps are built once per containing member.
// Must not concatenate token text, reparse an analyzer tree, retain trees across compilations or perform file I/O.

using System.Globalization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kimi.Analyzers;

internal sealed class CodeRulesSource(Compilation compilation, SyntaxTree tree, string path, CancellationToken cancellation)
{
    private readonly SourceText text = tree.GetText(cancellation);
    private SemanticModel? semantics;
    private Dictionary<SyntaxNode, string?>? identities;
    private Dictionary<SyntaxNode, Dictionary<LocalFunctionStatementSyntax, string>>? locals;

    internal string Path => path;

    internal SyntaxNode Root { get; } = tree.GetRoot(cancellation);

    internal SourceText Text => this.text;

    internal SemanticModel Semantics => this.semantics ??= compilation.GetSemanticModel(tree);

    internal List<CodeRuleObservation>? Observations { get; private set; }

    internal static int CountTokens(string source)
    {
        foreach (var trivia in SyntaxFactory.ParseLeadingTrivia(source))
        {
            if ((trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)) &&
                trivia.ToString().IndexOf("<auto-generated", StringComparison.Ordinal) >= 0)
            {
                return 0;
            }
        }

        return CountTokens(CSharpSyntaxTree.ParseText(source).GetRoot());
    }

    internal static int CountTokens(SyntaxNode root)
    {
        var count = 0;
        foreach (var token in root.DescendantTokens())
        {
            if (!token.IsMissing && !token.IsKind(SyntaxKind.EndOfFileToken))
            {
                count++;
            }
        }

        return count;
    }

    internal void Record(CodeRule rule, SyntaxNode node, int value, int limit, string? anchor)
    {
        if (anchor is null)
        {
            return;
        }

        this.AddObservation(rule, anchor == "file" ? path : this.Scope(node), anchor, node.GetLocation(), value, limit);
    }

    internal void RecordLine(CodeRule rule, TextLine line, int limit)
    {
        var position = line.Start;
        while (position < line.End && char.IsWhiteSpace(this.text[position]))
        {
            position++;
        }

        var node = this.Root.FindToken(position).Parent!;
        while (node.Parent is not null && !node.Span.Contains(position))
        {
            node = node.Parent;
        }

        this.AddObservation(rule, this.Scope(node), this.LineAnchor(line.LineNumber), Location.Create(tree, line.Span), line.Span.Length, limit);
    }

    internal string Scope(SyntaxNode node)
    {
        for (var parent = node; parent is not null; parent = parent.Parent)
        {
            if (parent is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax && this.Identity(parent) is { } identity)
            {
                return identity;
            }
        }

        return path;
    }

    internal string? MemberAnchor(SyntaxNode member)
    {
        if (member is not LocalFunctionStatementSyntax local)
        {
            return this.Identity(member) is { } identity ? "member:" + identity : null;
        }

        var owner = this.LocalOwner(local);
        this.locals ??= new();
        if (!this.locals.TryGetValue(owner, out var anchors))
        {
            anchors = this.LocalAnchors(owner);
            this.locals.Add(owner, anchors);
        }

        return anchors[local];
    }

    internal void RecordMember(CodeRule rule, SyntaxNode declaration, ISymbol symbol, int value, int limit)
    {
        this.identities ??= new();
        this.identities[declaration] = symbol.GetDocumentationCommentId();
        this.Record(rule, declaration, value, limit, this.MemberAnchor(declaration));
    }

    internal string NodeAnchor(IEnumerable<SyntaxToken> tokens)
    {
        var hash = 14695981039346656037UL;
        var first = true;
        foreach (var token in tokens)
        {
            if (token.IsMissing || token.IsKind(SyntaxKind.EndOfFileToken))
            {
                continue;
            }

            if (!first)
            {
                HashByte(ref hash, 32);
            }

            this.HashSpan(ref hash, token.Span);
            first = false;
        }

        return "node:" + hash.ToString("x16", CultureInfo.InvariantCulture);
    }

    internal string LineAnchor(int lineNumber)
    {
        var span = this.text.Lines[lineNumber].Span;
        var end = span.End;
        while (end > span.Start && char.IsWhiteSpace(this.text[end - 1]))
        {
            end--;
        }

        var hash = 14695981039346656037UL;
        this.HashSpan(ref hash, TextSpan.FromBounds(span.Start, end));
        return "line:" + hash.ToString("x16", CultureInfo.InvariantCulture);
    }

    private static string LocalPath(LocalFunctionStatementSyntax local, SyntaxNode owner)
    {
        var names = new Stack<string>();
        for (SyntaxNode? node = local; node is not null && node != owner; node = node.Parent)
        {
            if (node is LocalFunctionStatementSyntax function)
            {
                names.Push(function.Identifier.ValueText);
            }
        }

        return string.Join("/", names);
    }

    private static void HashByte(ref ulong hash, byte value) => hash = unchecked((hash ^ value) * 1099511628211UL);

    private void AddObservation(CodeRule rule, string scope, string anchor, Location location, int value, int limit)
    {
        this.Observations ??= [];
        this.Observations.Add(new CodeRuleObservation(new CodeRuleKey(rule, scope, anchor), path, location, value, limit));
    }

    private string? Identity(SyntaxNode declaration)
    {
        this.identities ??= new();
        if (!this.identities.TryGetValue(declaration, out var identity))
        {
            identity = this.Semantics.GetDeclaredSymbol(declaration, cancellation)?.GetDocumentationCommentId();
            this.identities.Add(declaration, identity);
        }

        return identity;
    }

    private SyntaxNode LocalOwner(LocalFunctionStatementSyntax local)
    {
        foreach (var ancestor in local.Ancestors())
        {
            if (ancestor is MemberDeclarationSyntax or VariableDeclaratorSyntax && this.Identity(ancestor) is not null)
            {
                return ancestor;
            }
        }

        return this.Root;
    }

    private Dictionary<LocalFunctionStatementSyntax, string> LocalAnchors(SyntaxNode owner)
    {
        var prefix = "local:" + (owner == this.Root ? "file:" + path : this.Identity(owner)) + "/";
        var functions = owner.DescendantNodes().OfType<LocalFunctionStatementSyntax>().Where(x => this.LocalOwner(x) == owner).ToArray();
        var paths = new string[functions.Length];
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);
        for (var i = 0; i < functions.Length; i++)
        {
            var name = paths[i] = LocalPath(functions[i], owner);
            counts.TryGetValue(name, out var count);
            counts[name] = count + 1;
        }

        var ordinals = new Dictionary<string, int>(StringComparer.Ordinal);
        var anchors = new Dictionary<LocalFunctionStatementSyntax, string>();
        for (var i = 0; i < functions.Length; i++)
        {
            var name = paths[i];
            ordinals.TryGetValue(name, out var ordinal);
            ordinals[name] = ++ordinal;
            anchors.Add(functions[i], prefix + name + (counts[name] > 1 ? "#" + ordinal.ToString(CultureInfo.InvariantCulture) : string.Empty));
        }

        return anchors;
    }

    // Stream UTF-8 FNV-1a bytes from the existing source text; CRLF hashes like LF.
    private void HashSpan(ref ulong hash, TextSpan span)
    {
        for (var i = span.Start; i < span.End; i++)
        {
            var value = (int)this.text[i];
            if (value == '\r' && i + 1 < span.End && this.text[i + 1] == '\n')
            {
                continue;
            }

            if (char.IsHighSurrogate((char)value) && i + 1 < span.End && char.IsLowSurrogate(this.text[i + 1]))
            {
                value = char.ConvertToUtf32((char)value, this.text[++i]);
            }
            else if (char.IsSurrogate((char)value))
            {
                value = 0xfffd;
            }

            if (value < 0x80)
            {
                HashByte(ref hash, (byte)value);
            }
            else
            {
                if (value >= 0x10000)
                {
                    HashByte(ref hash, (byte)(0xf0 | (value >> 18)));
                    HashByte(ref hash, (byte)(0x80 | ((value >> 12) & 0x3f)));
                }
                else if (value >= 0x800)
                {
                    HashByte(ref hash, (byte)(0xe0 | (value >> 12)));
                }
                else
                {
                    HashByte(ref hash, (byte)(0xc0 | (value >> 6)));
                }

                if (value >= 0x800)
                {
                    HashByte(ref hash, (byte)(0x80 | ((value >> 6) & 0x3f)));
                }

                HashByte(ref hash, (byte)(0x80 | (value & 0x3f)));
            }
        }
    }
}
